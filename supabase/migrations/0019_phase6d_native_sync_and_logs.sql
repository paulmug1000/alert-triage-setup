-- PULSE ECOSYSTEM — MIGRATION 0019: PHASE 6D NATIVE SYNC, WRITE-BACKS & LOGS
-- ============================================================================
-- Replaces the remaining virtual Master grids (`AutoLog`, `GasExecLogs`,
-- `Year0Data`, `RevComp`, `StarterPL`, `StarterInv`, `MgmtRep`, and
-- client-linked transient tabs) and Recon `master_sheet_grids` reads/writes
-- with normalized Postgres tables and direct `pulse_master_sync_configs`
-- columns so `sync_orchestrator_mode = 'native'` runs with zero
-- `master_sheet_grids` I/O.
--
-- Security model (AGENTS.md Rule 15):
-- 1. Row-Level Security (RLS) is enabled on all new tables with explicit
--    default-deny policies for `anon` and `authenticated`; runtime access runs
--    exclusively server-side via `service_role`.
-- 2. All tenant data is scoped by `client_id` / `client_name` with ON DELETE CASCADE.
-- ============================================================================

-- ============================================================================
-- 1. PHASE 6D ORCHESTRATOR MODE FLAG ON `public.clients`
-- ============================================================================
ALTER TABLE public.clients
  ADD COLUMN IF NOT EXISTS sync_orchestrator_mode TEXT NOT NULL DEFAULT 'grid_gas';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'clients_sync_orchestrator_mode_check'
      AND conrelid = 'public.clients'::regclass
  ) THEN
    ALTER TABLE public.clients
      ADD CONSTRAINT clients_sync_orchestrator_mode_check
      CHECK (sync_orchestrator_mode IN ('grid_gas', 'shadow', 'native'));
  END IF;
END $$;

-- ============================================================================
-- 2. PHASE 6D: `public.pulse_automation_logs` (replaces `master::AutoLog`)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.pulse_automation_logs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id UUID NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
  client_name TEXT NOT NULL,
  sort_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
  logged_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  raw_timestamp_cell JSONB NOT NULL DEFAULT '""'::jsonb,
  timestamp_display TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT '',
  summary TEXT NOT NULL DEFAULT '',
  details TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT 'automator',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_pulse_automation_logs_client_seq
  ON public.pulse_automation_logs (client_id, sort_seq DESC);

CREATE INDEX IF NOT EXISTS idx_pulse_automation_logs_name_seq
  ON public.pulse_automation_logs (client_name, sort_seq DESC);

ALTER TABLE public.pulse_automation_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS pulse_automation_logs_deny_all_anon ON public.pulse_automation_logs;
CREATE POLICY pulse_automation_logs_deny_all_anon
  ON public.pulse_automation_logs
  FOR ALL
  TO anon, authenticated
  USING (false)
  WITH CHECK (false);

REVOKE ALL ON TABLE public.pulse_automation_logs FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.pulse_automation_logs TO postgres, service_role;

